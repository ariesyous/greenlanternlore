// Publish complete character HTML from the same markup used by legacy links.
// Run after editing character data, the profile template, or search/page inventory.
const fs = require('node:fs');
const path = require('node:path');
const { renderCharacter } = require('../js/character.js');
const root = path.resolve(__dirname, '..');
const siteUrl = 'https://ariesyous.github.io/greenlanternlore/';
const sections = ['characters', 'corps', 'entities', 'eras', 'events', 'explained', 'glossary', 'guardians', 'moments', 'powers', 'screen', 'stories', 'villains', 'worlds'];
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const escape = value => String(value).replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;');
const decode = value => value.replaceAll('&quot;', '"').replaceAll('&lt;', '<').replaceAll('&gt;', '>').replaceAll('&amp;', '&');

function buildSite({ check = false } = {}) {
  const characters = JSON.parse(read('data/characters.json')).characters;
  const ids = new Set();
  for (const character of characters) {
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(character.id) || ids.has(character.id)) throw new Error('Invalid or duplicate character ID: ' + character.id);
    ids.add(character.id);
  }
  const outputs = new Map();
  const template = read('character.html').replace(/\r\n/g, '\n');
  for (const c of characters) {
    const file = `characters/${c.id}.html`;
    const title = `${c.name}: ${c.corps} Profile | Lantern Lore`;
    const description = (c.summary || c.tagline).slice(0, 155);
    const url = siteUrl + file;
    const image = siteUrl + (c.portraitWithheld ? 'assets/og-preview.jpg' : c.portrait);
    const metadata = `  <title>${escape(title)}</title>
  <meta name="description" content="${escape(description)}" />
  <link rel="canonical" href="${url}" />
  <meta property="og:type" content="website" />
  <meta property="og:site_name" content="Lantern Lore" />
  <meta property="og:title" content="${escape(title)}" />
  <meta property="og:description" content="${escape(description)}" />
  <meta property="og:url" content="${url}" />
  <meta property="og:image" content="${image}" />
  <meta property="og:image:alt" content="${escape(c.portraitWithheld ? 'Lantern Lore' : c.name)}" />
  <meta name="twitter:card" content="summary_large_image" />
  <meta name="twitter:title" content="${escape(title)}" />
  <meta name="twitter:description" content="${escape(description)}" />
  <meta name="twitter:image" content="${image}" />`;
    const html = template
      .replace(/  <title>[^<]*<\/title>\n  <meta name="description"[^>]*\/>/, () => metadata)
      .replace(/\s*<script src="js\/character.js"[^>]*><\/script>/, '')
      .replace(/<noscript>[\s\S]*?<\/noscript>\n?/, '')
      .replace(/(<div id="character-detail" class="explainer">)\s*<p>Loading…<\/p>/, (_, opening) => `${opening}\n      ${renderCharacter(c)}`)
      .replace(/\b(href|src)="([^"]+)"/g, (match, attr, ref) => /^(?:[a-z][a-z0-9+.-]*:|\/|#)/i.test(ref) ? match : `${attr}="../${ref}"`)
      .replace('<!DOCTYPE html>', '<!DOCTYPE html>\n<!-- Generated by scripts/build-character-pages.cjs; edit data/characters.json or character.html. -->')
      .replace(/[ \t]+$/gm, '');
    if (!html.includes(`<h1>${escape(c.name)}</h1>`) || html.includes('Loading…')) throw new Error('Profile template could not be filled: ' + c.id);
    outputs.set(file, html);
  }

  // Keep editorial search terms for other pages; character previews come from the roster.
  const oldEntries = JSON.parse(read('data/search-index.json'));
  const pageEntries = oldEntries.filter(entry => !/^character\.html\?id=|^characters\//.test(entry.u)).map(entry => {
    if (!['index.html', 'timeline.html', 'explained/geoff-johns.html', 'screen/lanterns-hbo.html'].includes(entry.u)) return entry;
    const html = read(entry.u);
    const t = decode(html.match(/<title>([^<]+)<\/title>/)[1]).replace(/(?: — | \| )Lantern Lore$/, '');
    const s = decode(html.match(/<meta name="description" content="([^"]*)"/)[1]);
    return { ...entry, t, s, k: `${t} ${s} ${entry.u}`.toLowerCase() };
  });
  const characterEntries = characters.map(c => ({
    t: c.name,
    s: `${c.corps} — ${c.summary || c.tagline}`,
    u: `characters/${c.id}.html`,
    k: `${c.name} ${c.id.replaceAll('-', ' ')} ${c.corps} ${c.summary || ''} ${c.tagline} ${c.firstAppearance}`.toLowerCase()
  }));
  outputs.set('data/search-index.json', JSON.stringify([...characterEntries, ...pageEntries]) + '\n');

  const pages = fs.readdirSync(root).filter(file => file.endsWith('.html') && !['404.html', 'character.html'].includes(file));
  for (const section of sections) {
    if (section === 'characters') {
      pages.push(...characters.map(c => `characters/${c.id}.html`));
      continue;
    }
    for (const file of fs.readdirSync(path.join(root, section), { recursive: true })) {
      if (file.endsWith('.html')) pages.push(`${section}/${file.replaceAll('\\', '/')}`);
    }
  }
  outputs.set('sitemap.xml', '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' +
    pages.sort().map(file => `  <url><loc>${siteUrl}${file === 'index.html' ? '' : file}</loc></url>`).join('\n') + '\n</urlset>\n');

  const stale = [];
  for (const [file, content] of outputs) {
    const target = path.join(root, file);
    if (fs.existsSync(target) && read(file).replace(/\r\n/g, '\n') === content) continue;
    stale.push(file);
    if (!check) {
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(target, content);
    }
  }
  if (check && stale.length) throw new Error(`Generated files need updating. Run node scripts/build-character-pages.cjs:\n${stale.join('\n')}`);
  return { profiles: characters.length, urls: pages.length, updated: stale.length };
}

module.exports = { buildSite };
if (require.main === module) {
  try {
    const result = buildSite({ check: process.argv.includes('--check') });
    console.log(`${result.profiles} static profiles; ${result.urls} sitemap URLs; ${result.updated} files ${process.argv.includes('--check') ? 'out of date' : 'updated'}.`);
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
